-- Text content is data: named parameters assemble existing painted glyphs.
-- Templates are compiled once; changing counters never creates a string cache.
-- Every text the player reads is here (plan v10 V6), under an id, in the
-- base language; another language (Text.language) gives its own template
-- for any id, the base one standing in for a missing id, and Text.use makes
-- it the one every screen reads from then on. Content definitions name
-- their texts by id (a weapon's name, a creature's card...).
local Registry = require('src.core.registry')
local Text = { base = 'en' }
local registry = Registry:new('text key')
local languages, active = {}, 'en'
local function compile(id, template)
  assert(type(template) == 'string', 'text key ' .. tostring(id) .. ': expected template')
  local tokens, position, dynamic = {}, 1, false
  while position <= #template do
    local first, last, name = template:find('{([%a_][%w_]*)}', position)
    local literal = template:sub(position, first and first - 1 or #template)
    assert(not literal:find('[{}]'), 'text key ' .. tostring(id) .. ': invalid placeholder')
    tokens[#tokens + 1] = { literal = literal }
    if not first then
      break
    end
    tokens[#tokens + 1] = { parameter = name }
    dynamic = true
    position = last + 1
  end
  return { template = template, tokens = tokens, dynamic = dynamic }
end
function Text.register(id, template)
  assert(not registry:has(id), 'text key already registered: ' .. tostring(id))
  return registry:register(id, compile(id, template))
end
function Text.unregister(id)
  return registry:unregister(id)
end
function Text.each()
  return registry:each()
end
function Text.has(id)
  return registry:has(id)
end
-- A language: its templates by id (every id must exist in the base) and,
-- optionally, its own painted inscriptions (ui/fonts/painted_titles.lua
-- atlas metadata); without them a painted title is drawn in glyphs.
function Text.language(name, templates, paintings)
  assert(type(name) == 'string' and name ~= Text.base, 'a language needs its own name')
  local compiled = {}
  for id, template in pairs(templates) do
    assert(registry:has(id), 'language ' .. name .. ': unknown text key ' .. tostring(id))
    compiled[id] = compile(id, template)
  end
  languages[name] = { entries = compiled, paintings = paintings }
end
-- Read every text from language name from now on (the base: Text.base).
function Text.use(name)
  assert(name == Text.base or languages[name], 'unknown language ' .. tostring(name))
  active = name
end
function Text.active()
  return active
end
-- The painted inscriptions of the active language (nil: draw glyphs).
function Text.paintings()
  if active == Text.base then
    return true
  end
  return languages[active].paintings
end
-- What a name shows: the text of a key, or a name already written (a
-- label made with Text.get, a station dummy's).
function Text.show(name)
  if registry:has(name) then
    return Text.get(name)
  end
  return name
end
function Text.get(id, parameters)
  local entry = registry:get(id)
  local language = languages[active]
  if language and language.entries[id] then
    entry = language.entries[id]
  end
  if not entry.dynamic then
    return entry.template
  end
  local out = {}
  for _, token in ipairs(entry.tokens) do
    if token.literal then
      out[#out + 1] = token.literal
    else
      local value = parameters and parameters[token.parameter]
      assert(
        type(value) == 'string'
          or (type(value) == 'number' and value == value and math.abs(value) < math.huge),
        'text key ' .. id .. ': missing/invalid parameter ' .. token.parameter
      )
      out[#out + 1] = tostring(value)
    end
  end
  return table.concat(out)
end
