local function attackUV(pixels, edge)
  local uv = {}
  for i, value in ipairs(pixels) do
    uv[i] = value / (edge or 362)
  end
  return uv
end
local function appendMarks(marks, offset, edge, cloak)
  for cell, mark in ipairs(marks) do
    local p = base()
    local cloth = part('looseCloak', false, 'cloth', attackUV(cloak, edge))
    cloth.hittable = false
    add(p, cloth)
    add(p, part('torso', 'torso', 'metal', attackUV(mark.torso, edge)))
    for i, poly in ipairs(mark.legs) do
      add(p, part('leg' .. i, 'lower', 'metal', attackUV(poly, edge)))
    end
    for i, poly in ipairs(mark.arms) do
      add(p, part('arm' .. i, 'torso', 'metal', attackUV(poly, edge)))
    end
    for i, b in ipairs(mark.hands) do
      add(p, box('hand' .. i, 'torso', 'flesh', unpack(attackUV(b, edge))))
    end
    add(p, box('head', 'head', 'flesh', unpack(attackUV(mark.head, edge))))
    Armored.frames[offset + cell] = { parts = p, anchors = { claw = attackUV(mark.claw, edge) } }
  end
end
