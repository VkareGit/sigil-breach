local function part(id, zone, material, polygon)
  local p = {}
  for i = 1, #polygon, 2 do
    p[i], p[i + 1] = polygon[i] / CELL_W, polygon[i + 1] / CELL_H
  end
  return Author.part(id, zone, material, p)
end
local function box(id, zone, material, x1, y1, x2, y2)
  return part(id, zone, material, { x1, y1, x2, y1, x2, y2, x1, y2 })
end
