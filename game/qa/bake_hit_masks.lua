-- Offline build step. Produces immutable CPU masks; never modifies source art.
-- Each frame's pigment is classified exactly as the sprite shader draws it
-- (qa/hit_truth.lua), stored run-length (content/art/mask_codec.lua) and
-- bound to its source bytes, exact rectangle, filter and classifier, so a
-- changed atlas or frame cut fails anatomy-data instead of silently shifting
-- what shots meet. PNG access and hashing happen only in the baker and QA.
local Art = require('src.content.enemy_art')
local Ability = require('src.content.ability_art')
local Codec = require('src.content.art.mask_codec')
local Truth = require('qa.hit_truth')
local Provenance = require('qa.mask_provenance')
local Serialize = require('src.core.serialize')
local Sizes = require('src.content.art.sources')
local Bake = {}
local function raster(truth, region, path, linear)
  local grid = Truth.grid
  local data = love.image.newImageData(path)
  local w, h = data:getDimensions()
  data:release()
  assert(
    Sizes[path] and w == Sizes[path][1] and h == Sizes[path][2],
    'update source dimensions before baking: ' .. path
  )
  local p = { region = region, path = path, width = w, height = h, linear = linear, live = true }
  local rows = {}
  for y = 0, grid - 1 do
    local row, code = {}, 0
    for x = 0, grid - 1 do
      local class = truth:texelUncached(p, x, y)
      code = code * 4 + (class == 'body' and 1 or (class == 'contour' and 2 or 0))
      if x % 2 == 1 then
        row[#row + 1] = string.format('%x', code)
        code = 0
      end
    end
    rows[#rows + 1] = table.concat(row)
  end
  local tokens = Codec.encode(rows, grid)
  local decoded = Codec.decode(tokens, grid)
  for y = 1, grid do
    assert(decoded[y] == rows[y], 'mask codec round trip failed: ' .. path)
  end
  return tokens, decoded
end
-- The same baker for a single fixture frame; no output file or source edit.
function Bake.frame(region, path, linear)
  local truth = setmetatable({ data = {}, sizes = {} }, Truth)
  local tokens, decoded = raster(truth, region, path, linear)
  truth:release()
  return decoded, tokens
end
function Bake.run(destination)
  local truth = setmetatable({ data = {}, sizes = {} }, Truth)
  local grid = Truth.grid
  local count = 0
  local sources = Provenance.capture(Provenance.frames())
  local function frame(region, path, linear)
    count = count + 1
    return "'" .. raster(truth, region, path, linear) .. "'"
  end
  local masks = { layouts = {}, abilities = {} }
  local function group(name, id, regions, pathOf, linearOf)
    local tokens = {}
    for index, region in ipairs(regions) do
      tokens[index] = frame(region, pathOf(region), linearOf(region))
    end
    masks[name][#masks[name] + 1] =
      string.format("['%s'] = {\n%s,\n},", id, table.concat(tokens, ',\n'))
  end
  for _, kind in ipairs(Art.kinds) do
    group('layouts', kind, Art.layouts[kind].frames, function(region)
      return region.sourcePath
    end, function(region)
      return region.filter == 'linear'
    end)
  end
  for key, entry in Ability.each() do
    group('abilities', key, entry.frames, function()
      return entry.path
    end, function()
      return false
    end)
  end
  local out = assert(io.open(destination, 'w'))
  out:write(
    '-- Generated by qa/bake_hit_masks.lua from existing painted alpha. Do not hand edit.\n'
      .. '-- Run-length tokens (content/art/mask_codec.lua), decoded once on load;\n'
      .. '-- sources: source-byte SHA-256, exact UV/pixel rectangles, filters and classifier.\n'
      .. "return require('src.content.art.mask_codec').load({\n"
      .. 'grid = '
      .. grid
      .. ',\nlayouts = {\n'
      .. table.concat(masks.layouts, '\n')
      .. '\n},\nabilities = {\n'
      .. table.concat(masks.abilities, '\n')
      .. '\n},\nsources = '
      .. Serialize.encode(sources)
      .. '\n})\n'
  )
  out:close()
  truth:release()
  return count
end
return Bake
